// Part of `npm run build`: bundles the Vercel function for /api/assistant
// (server/vercelAssistant.ts -> api/assistant.js). One plain ESM file, so the function does
// not depend on how Vercel compiles and resolves this repository's TypeScript imports.
// npm packages stay external. The output is committed: Vercel lists the functions under
// api/ before the build runs.
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'rolldown';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

await build({
  cwd: ROOT,
  input: 'server/vercelAssistant.ts',
  platform: 'node',
  external: [/^node:/, /^@anthropic-ai\//],
  logLevel: 'warn',
  output: {
    file: 'api/assistant.js',
    format: 'esm',
    banner: '// Generated by scripts/build-api.mjs from server/vercelAssistant.ts. Do not edit.',
  },
});
