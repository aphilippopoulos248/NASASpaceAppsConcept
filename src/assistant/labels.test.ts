// The marking of replies and the standing note in the drawer (NASA's guidelines for AI
// applications; docs/lunyx/AI-USE.md F2 and F3), and that deterministic mode never attributes
// an answer to NASA (F1).
import { describe, expect, it } from 'vitest';
import { actionLog } from '../core/actions';
import { DeterministicEngine } from './deterministic/engine';
import { EXAMPLES } from './deterministic/examples';
import { ACCURACY_NOTE_MODEL, ACCURACY_NOTE_NO_MODEL, accuracyNote, isLanguageModel, replyLabel } from './labels';
import { DETERMINISTIC_LABEL } from './protocol';
import { ALL_ACTIONS, installFakeApp } from './testing/fakeApp';

describe('reply labels and the standing note', () => {
  it('marks a language model reply as AI-generated, with the model', () => {
    expect(replyLabel({ kind: 'model', label: 'Claude Opus 5.5', provider: 'anthropic' })).toBe('AI-generated · Claude Opus 5.5');
  });

  it('labels deterministic mode and the scripted test model as what they are, not as AI', () => {
    expect(replyLabel({ kind: 'deterministic' })).toBe(DETERMINISTIC_LABEL);
    expect(replyLabel({ kind: 'model', label: 'Scripted test model (not a language model)', provider: 'scripted' })).toBe('Scripted test model (not a language model)');
    // A source without a provider (an older history) is not claimed to be a model either.
    expect(replyLabel({ kind: 'model', label: 'Something' })).toBe('Something');
    expect(replyLabel(undefined)).toBe('');
    expect(isLanguageModel({ provider: 'scripted' })).toBe(false);
    expect(isLanguageModel(null)).toBe(false);
  });

  it('states where answers come from and that NASA is not responsible for their accuracy', () => {
    expect(accuracyNote({ provider: 'anthropic' })).toBe("Answers are generated by an AI model from Lunyx's own results. NASA is not responsible for their accuracy and has not reviewed them.");
    expect(accuracyNote({ provider: 'scripted' })).toBe(ACCURACY_NOTE_NO_MODEL);
    expect(accuracyNote(null)).toBe(ACCURACY_NOTE_NO_MODEL);
    for (const note of [ACCURACY_NOTE_MODEL, ACCURACY_NOTE_NO_MODEL]) expect(note).toContain('NASA is not responsible for their accuracy and has not reviewed them.');
  });
});

describe('deterministic mode never attributes an answer to NASA', () => {
  const FORBIDDEN = [/according to nasa/i, /\bnasa\s+(has\s+|have\s+)?(reviewed|approved|endorsed|verified|confirmed|says|said|states)\b/i, /\b(per|from)\s+nasa\b(?!\s+(pgda|svs|lro|lola|lroc|moon trek|trek|horizons|pds|product))/i];
  const EXTRA = ['site science', 'what is the long-term average sunlight here?', 'temperature', 'shadowcam', 'nearest ice targets', 'what is the illumination?', 'where is the earth?', 'help', '/actions', 'list the landing sites', 'show the average sunlight map'];

  it('in every example reply, and in the science, help and listing replies', async () => {
    const replies: string[] = [];
    for (const say of [...EXAMPLES.map((e) => e.say), ...EXTRA]) {
      installFakeApp(ALL_ACTIONS);
      const e = new DeterministicEngine(undefined, { wait: () => Promise.resolve() });
      for (const g of EXAMPLES.find((x) => x.say === say)?.given ?? ['go to IM-2']) await e.reply(g);
      replies.push((await e.reply(say)).text);
    }
    expect(actionLog().length).toBeGreaterThan(0);
    for (const text of replies) for (const bad of FORBIDDEN) expect(text, text).not.toMatch(bad);
  });
});
