// What the drawer writes under each reply and in its standing note, following NASA's
// guidelines for AI applications that use NASA data (docs/lunyx/AI-USE.md, section 1.4 and
// findings F2 and F3):
//   - a reply written by a language model is marked as AI-generated, with the model's name;
//   - deterministic mode and the scripted test model are not language models, and their
//     replies say what they are instead (marking them "AI-generated" would be untrue);
//   - a permanent note says where the answers come from and that NASA is not responsible
//     for their accuracy and has not reviewed them.
import { DETERMINISTIC_LABEL, type ModelInfo } from './protocol';

/** The provider id of the scripted test model (server/llm/scripted.ts). */
export const SCRIPTED_PROVIDER = 'scripted';

export const AI_GENERATED = 'AI-generated';

/** Who wrote a reply, as the session records it. */
export type ReplySource = { kind: 'model'; label: string; provider?: string } | { kind: 'deterministic' };

/** True for a language model; false for the scripted test model, and when nothing is known. */
export function isLanguageModel(info: Pick<ModelInfo, 'provider'> | { provider?: string } | null | undefined): boolean {
  return Boolean(info?.provider) && info!.provider !== SCRIPTED_PROVIDER;
}

/** The label under a reply: "AI-generated · Claude Opus 5.5", "Deterministic mode: no language model", "Scripted test model (not a language model)". */
export function replyLabel(source: ReplySource | undefined): string {
  if (!source) return '';
  if (source.kind === 'deterministic') return DETERMINISTIC_LABEL;
  return isLanguageModel(source) ? `${AI_GENERATED} · ${source.label}` : source.label;
}

/** The standing note when a language model answers (the wording of AI-USE.md, F3). */
export const ACCURACY_NOTE_MODEL = "Answers are generated by an AI model from Lunyx's own results. NASA is not responsible for their accuracy and has not reviewed them.";
/** The same note when no language model answers: deterministic mode, or the scripted test model. */
export const ACCURACY_NOTE_NO_MODEL = "Answers are worked out from Lunyx's own results, without an AI model. NASA is not responsible for their accuracy and has not reviewed them.";

/** The note for what answers now: a language model, or not (deterministic mode, the scripted test model, or still checking). */
export function accuracyNote(model: Pick<ModelInfo, 'provider'> | null | undefined): string {
  return isLanguageModel(model) ? ACCURACY_NOTE_MODEL : ACCURACY_NOTE_NO_MODEL;
}
